// Bundle the server simulation (src/server/sim.ts + the engine it imports) into one ESM file the
// Vercel Node runtime can load: api/_gen/sim.js. `npm run build:sim` writes it (part of `npm run build`);
// `node scripts/build-sim.mjs --check` fails if the committed file is out of date (part of `npm run check`).
// The output is committed so Vercel functions never depend on build-step ordering.
import { readFileSync, writeFileSync } from 'node:fs';
import { build } from 'rolldown';

const OUT = 'api/_gen/sim.js';
const result = await build({
  input: 'src/server/sim.ts',
  platform: 'node',
  logLevel: 'warn',
  // npm dependencies stay external: Vercel installs them and traces them from this file.
  external: ['three', 'zod', 'simplex-noise', 'alea'],
  write: false,
  output: {
    format: 'esm',
    banner:
      '// GENERATED by scripts/build-sim.mjs from src/server/sim.ts — do not edit.\n/* eslint-disable */',
    minify: false,
  },
});
const code = result.output[0].code;

if (process.argv.includes('--check')) {
  let current = '';
  try {
    current = readFileSync(OUT, 'utf8');
  } catch {
    /* missing */
  }
  if (current !== code) {
    console.error(`${OUT} is out of date — run: npm run build:sim`);
    process.exit(1);
  }
  console.log(`${OUT} is up to date`);
} else {
  writeFileSync(OUT, code);
  console.log(`wrote ${OUT} (${(code.length / 1024).toFixed(0)} KB)`);
}
